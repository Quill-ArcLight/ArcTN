"""Python adapters for ArcTN, opt_einsum, cotengra, and quimb.

Example::

    from quimb.tensor import Circuit
    from arctn import ArcTNOptimizer

    circ = Circuit.from_openqasm2_file("foo.qasm")
    amp = circ.amplitude("0" * circ.N, optimize=ArcTNOptimizer())

The optimizer works with quimb tasks such as ``amplitude``, ``sample``,
``local_expectation``, ``compute_marginal``, ``partial_trace``, and
``to_dense`` without task-specific glue code.

Public entry points
-------------------
============================  ==========================================================
``arctn_path``                Finds one contraction path with a Light or Heavy preset.
``ArcTNOptimizer``            Returns paths to opt_einsum and trees to cotengra.
``arctn_tree``                Builds a cotengra ``ContractionTree``, including slices.
``arctn_contract``            Plans, slices when requested, and executes with an
                              explicit native or opt_einsum array backend.
``arctn_plan``                Returns an immutable, serializable execution plan.
``ArcTNExecutionPlan``       Validates, converts, compiles, or executes one plan.
``ArcTNCompiledContraction``  Reuses a fixed network and SSA path.
``arctn_schedule``            Returns the final path, metrics, and slice plan.
``arctn_simplify``            Reports deterministic simplification without planning.
============================  ==========================================================

Interface conventions
---------------------
1. Python maps arbitrary hashable labels to ArcTN's ``u32`` leg identifiers.
2. Public path-only calls return opt_einsum-style recycled linear paths by
   default. Tree and execution helpers use SSA paths internally.
3. cotengra receives one-character symbols generated by ``oe.get_symbol()``.

"""

