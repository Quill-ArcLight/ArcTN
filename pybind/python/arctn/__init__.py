def _validate_auto_preset(value):
    if not isinstance(value, str) or value not in _AUTO_PRESETS:
        raise ValueError(
            "preset 只支持 'light' 或 'heavy'，"
            f"收到 {value!r}"
        )
    return value


def _validate_slicing_mode(value, target_size):
    if not isinstance(value, str) or value not in _SLICING_MODES:
        raise ValueError(
            "slicing_mode 只支持 'fixed' 或 'dynamic'，"
            f"收到 {value!r}"
        )
    if value == "dynamic" and target_size is None:
        raise ValueError(
            "slicing_mode='dynamic' 时必须同时提供 target_size"
        )
    return value


def _validate_max_time(value):
    if value is None:
        return None
    try:
        value = float(value)
    except (TypeError, ValueError) as exc:
        raise TypeError("max_time 必须是有限且大于 0 的秒数") from exc
    if not math.isfinite(value) or value <= 0.0:
        raise ValueError("max_time 必须是有限且大于 0 的秒数")
    return value


def _validate_planner_weights(flops_weight, read_write_weight):
    values = []
    for name, value in (
        ("flops_weight", flops_weight),
        ("read_write_weight", read_write_weight),
    ):
        if isinstance(value, bool):
            raise TypeError(f"{name} 必须是有限非负数，不能是 bool")
        try:
            value = float(value)
        except (TypeError, ValueError) as exc:
            raise TypeError(f"{name} 必须是有限非负数") from exc
        if not math.isfinite(value) or value < 0.0:
            raise ValueError(f"{name} 必须是有限非负数")
        values.append(value)
    if values == [0.0, 0.0]:
        raise ValueError("flops_weight 和 read_write_weight 不能同时为 0")
    return tuple(values)


def _validate_bool(value, name):
    if not isinstance(value, bool):
        raise TypeError(f"{name} 必须是 bool")
    return value


def _count_arg(value, name, minimum):
    """Parse a Python integer without accepting bool as an accidental budget."""
    if isinstance(value, bool):
        raise TypeError(f"{name} 必须是整数，不能是 bool")
    try:
        value = operator.index(value)
    except TypeError as exc:
        raise TypeError(f"{name} 必须是整数，得到 {value!r}") from exc
    if value < minimum:
        relation = "大于 0" if minimum == 1 else "不小于 0"
        raise ValueError(f"{name} 必须{relation}，得到 {value}")
    if value > sys.maxsize:
        raise OverflowError(f"{name}={value} 超出当前平台 usize 范围 {sys.maxsize}")
    return value


def _validate_target_size(value):
    if value is None:
        return None
    return _count_arg(value, "target_size", 1)


def _validate_execution_backend(value):
    if not isinstance(value, str) or not value or value != value.strip():
        raise ValueError(
            "backend 必须是不带首尾空白的非空字符串，"
            f"收到 {value!r}"
        )
    if value == "auto":
        raise ValueError(
            "backend 必须显式指定；使用 'native'、'numpy' 或已安装的 "
            "opt_einsum 后端名，例如 'cupy'、'torch' 或 'jax'"
        )
    return value

